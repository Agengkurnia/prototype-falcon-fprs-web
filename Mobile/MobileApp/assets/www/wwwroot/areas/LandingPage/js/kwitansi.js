function downloadLetter() {
    let dataReq = {
        'Category': 'OTP',
        'KwitansiId': kwitnasiid
    };
    $.ajax({
        url: urlApiGlobal + '/promotion/kwitansi/downloadkwitansiletter',
        type: "POST",
        data: JSON.stringify(dataReq),
        timeout: 15000,
        contentType: "application/json",
        headers: {
            "Authorization": "Bearer " + token
        },
        xhrFields: {
            responseType: 'blob'
        },
        success: function (res) {
            $("#divsubmit").hide();
            $('button').prop('disabled', true);
            $('input').prop('disabled', true);

            Swal.fire({
                title: "<span id='save-popup-title'>Saving...</span>",
                html: "<div id='save-popup-icon'></div><span id='save-popup-message'></span>",
                confirmButtonColor: "#005d41",
                confirmButtonText: "Oke",
                allowOutsideClick: false,
                didOpen: () => {
                    Swal.showLoading();
                }
            }).then((result) => {
                if (result.isConfirmed) {
                    window.location.reload();
                }
            });

            popupTextElement = document.getElementById("save-popup-message");

            popupTextElement.innerHTML = popupTextElement.innerHTML + "<br/>Download Document Success";

            const file = new File([res], 'kwitansi.pdf', { type: res.type });
            if (ismaterai) {
                eMateraiGet(file);
            }
            else {
                uploadLetter(file);
            }
        },
        error: function (xhr, textStatus, errorThrown) {
            console.log('error exec downloadkwitansiletter ' + textStatus);
            popupTextElement.innerHTML = popupTextElement.innerHTML + "<br/>Download Document Error";
            document.getElementById("save-popup-icon").innerHTML = '<i class="fa fa-times" style="font-size: 100px; color: red;"><i/>';
            document.getElementById("save-popup-title").innerHTML = "Failed!";
        }
    });
}

function eMateraiGet(file) {
    var now = new Date();
    var formData = new FormData();
    var bodyData = {
        'objRequestData': {
            'intProgramId': progid,
            'intProgramOutletId': progoutid,
            'txtOrigNoDoc': docno,
            'TxtNamaFile': filename + '.pdf',
            'TxtNoDoc': filename,
            'DtTanggalDoc': now.toISOString(),
            'DecNilaiDoc': decNilaiDoc,
            'TxtLocation': branchName,
            'TxtReason': 'Dokumen Kwitansi'
        }
    };

    formData.append('file', file);
    formData.append('Data', JSON.stringify(bodyData));
    $.ajax({
        url: urlApiGlobal + '/POA/GenerateMateraiKwitansi_J',
        type: 'POST',
        data: formData,
        headers: {
            "Authorization": "Bearer " + token
        },
        processData: false,
        contentType: false,
        success: function (response) {
            if (response.bitSuccess) {
                popupTextElement.innerHTML = popupTextElement.innerHTML + "<br/>Generate Materai Success";
                getNewDocument(response.objData);
            }
            else {
                popupTextElement.innerHTML = popupTextElement.innerHTML + "<br/>Generate Materai Failed";
                swal.hideLoading();
                document.getElementById("save-popup-icon").innerHTML = '<i class="fa fa-times" style="font-size: 100px; color: red;"><i/>';
                document.getElementById("save-popup-title").innerHTML = "Failed!";
            }
        },
        error: function (xhr, textStatus, errorThrown) {
            console.log('error exec generate materai kwitansi ' + textStatus);
            popupTextElement.innerHTML = popupTextElement.innerHTML + "<br/>Generate Materai Error";
            swal.hideLoading();
            document.getElementById("save-popup-icon").innerHTML = '<i class="fa fa-times" style="font-size: 100px; color: red;"><i/>';
            document.getElementById("save-popup-title").innerHTML = "Failed!";
        }
    });
}

function getNewDocument(link) {
    $.ajax({
        url: urlApiGlobal + link,
        type: 'GET',
        headers: {
            "Authorization": "Bearer " + token
        },
        xhrFields: {
            responseType: 'blob'
        },
        contentType: false,
        success: function (res) {
            popupTextElement.innerHTML = popupTextElement.innerHTML + "<br/>Download New Document Success";
            let fileName = 'newkwitansi.pdf';
            if (res.size == 185792) { // Cek apakah size nya termasuk file "_blank"
                fileName = 'newkwitansi_blank.pdf';
            } else {
                fileName = 'newkwitansi.pdf';
            }
            const file = new File([res], fileName, { type: 'application/pdf' });
            //const file = new File([res], 'newkwitansi.pdf', { type: 'application/pdf' });
            uploadLetter(file);
        },
        error: function (xhr, textStatus, errorThrown) {
            console.log('error exec download new document ' + textStatus);
            popupTextElement.innerHTML = popupTextElement.innerHTML + "<br/>Download New Document Error";
            swal.hideLoading();
            document.getElementById("save-popup-icon").innerHTML = '<i class="fa fa-times" style="font-size: 100px; color: red;"><i/>';
            document.getElementById("save-popup-title").innerHTML = "Failed!";
        }
    });
}

function uploadLetter(file) {
    var formData = new FormData();

    formData.append('File', file);
    formData.append('AppCode', 'Falcon');
    formData.append('TransactionType', 'PoA');
    formData.append('TransactionNo', progid);
    formData.append('DocumentType', 'Kwitansi');
    formData.append('DocumentNo', docno);
    formData.append('IsOtp', true);
    $.ajax({
        url: urlApiGlobal + '/document/resourcedoc/uploadverifiedkwitansi',
        type: 'POST',
        data: formData,
        headers: {
            "Authorization": "Bearer " + token
        },
        processData: false,
        contentType: false,
        success: function (response) {
            popupTextElement.innerHTML = popupTextElement.innerHTML + "<br/>Upload Document has Uploaded";
            saveOtp();
        },
        error: function (xhr, textStatus, errorThrown) {
            console.log('error exec uploadverifiedkwitansi ' + textStatus);
            popupTextElement.innerHTML = popupTextElement.innerHTML + "<br/>Upload Document Error";
            swal.hideLoading();
            document.getElementById("save-popup-icon").innerHTML = '<i class="fa fa-times" style="font-size: 100px; color: red;"><i/>';
            document.getElementById("save-popup-title").innerHTML = "Failed!";
        }
    });
}

function saveOtp() {
    let dataReq = {
        'IntProgramId': progid,
        'IntProgramOutletId': progoutid,
        'TxtTipeDokumen': doctype,
        'TxtDocumentId': kwitnasiid,
        'TxtDocNo': docno,
        'TxtPhoneNumber': phoneno,
        'TxtOtpCode': $('#txtOtp').val(),
        'BitRefund': bitRefund,
        'DecTotalKwitansi': decTotalKwitansi
    };
    $.ajax({
        url: urlApiGlobal + '/prmadapter/syncdata/verifiedotp',
        type: "POST",
        data: JSON.stringify(dataReq),
        headers: {
            "Authorization": "Bearer " + token
        },
        dataType: "json",
        timeout: 15000,
        contentType: "application/json",
        success: function (res) {
            var jsonString = JSON.stringify(res);
            if (res.code == 200) {

                let divSecond = document.getElementsByClassName("signsecondparty");

                let tanggalSekarang = new Date();
                let tanggal = tanggalSekarang.getDate();
                let bulan = tanggalSekarang.getMonth();
                let tahun = tanggalSekarang.getFullYear();
                let jam = tanggalSekarang.getHours();
                let menit = tanggalSekarang.getMinutes().toString().padStart(2, '0');;

                let fulldate = tanggal + ' ' + monthFullName[bulan] + ' ' + tahun + ', ' + jam + ':' + menit;

                let isgenerated = '<span class="frame-generate">' +
                    '<span class="sptext">Tanda tangan perusahaan</span>' +
                    '<span class="spsystem"> Generated by system</span>' +
                    '<span class="sptext"> pada ' + fulldate + '</span>' +
                    '</span>';

                if (divSecond.length > 0 || !isverified) {
                    divSecond[0].style.cssText = '';
                    divSecond.innerHTML = "";
                    divSecond[0].innerHTML = isgenerated;
                }

                popupTextElement.innerHTML = popupTextElement.innerHTML + "<br/>Verified OTP Success";

                swal.hideLoading();

                document.getElementById("save-popup-icon").innerHTML = '<i class="fa fa-check-circle-o" style="font-size: 100px; color: green;"><i/>';

                document.getElementById("save-popup-title").innerHTML = "Success!";
            }
            else {
                console.log('error code API verifiedotp');
                popupTextElement.innerHTML = "OTP yang anda masukkan salah";
                swal.hideLoading();
                document.getElementById("save-popup-icon").innerHTML = '<i class="fa fa-times" style="font-size: 100px; color: red;"><i/>';
                document.getElementById("save-popup-title").innerHTML = "Failed!";
                $("#btnSave").prop('disabled', false);
            }
        },
        error: function (xhr, textStatus, errorThrown) {
            console.log('error exec verifiedotp ' + textStatus);
            popupTextElement.innerHTML = popupTextElement.innerHTML + "<br/>Verifikasi OTP Gagal";
            swal.hideLoading();
            document.getElementById("save-popup-icon").innerHTML = '<i class="fa fa-times" style="font-size: 100px; color: red;"><i/>';
            document.getElementById("save-popup-title").innerHTML = "Failed!";
            $("#btnSave").prop('disabled', false);
            getToken();
        }
    });
}
