function getToken() {
    return new Promise((resolve, reject) => {
        $.ajax({
            url: urlApiGlobal + '/apigateway/gettoken',
            type: "POST",
            dataType: "json",
            timeout: 15000,
            contentType: "application/json",
            success: function (res) {
                if (res.code == 200) {
                    token = res.obj.access_token;
                    resolve();
                }
            },
            error: function (xhr, textStatus, errorThrown) {

            }
        });
    });
}

